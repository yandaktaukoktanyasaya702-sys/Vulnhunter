# ─── HEADERS ─────────────────────────────────────────────────────────────────

def scan_headers(url):
    log(f"\n  [HEADERS] {url}", Fore.CYAN)
    headers_check = [
        ("X-Frame-Options",           "Prevents clickjacking"),
        ("X-XSS-Protection",          "Browser XSS filter"),
        ("X-Content-Type-Options",    "Prevents MIME sniffing"),
        ("Strict-Transport-Security", "Forces HTTPS"),
        ("Content-Security-Policy",   "Controls resource loading"),
        ("Referrer-Policy",           "Controls referrer info"),
    ]
    step("Fetching response headers")
    try:
        resp = waf_aware_get(url)
        if not resp:
            miss("No response")
            return
        attempt(f"HTTP {resp.status_code}")
        missing = []
        for header, desc in headers_check:
            if header in resp.headers:
                ok(f"{header}: {resp.headers[header][:60]}")
            else:
                miss(f"MISSING — {header} ({desc})")
                missing.append(header)
        if missing:
            FOUND_VULNS.append({"type":"Missing Headers","url":url,"missing":missing})
    except Exception as e:
        miss(f"Error: {e}")

