def scan_dirs(url):
    log(f"\n  [DIR BRUTE] {url}", Fore.CYAN)
    wordlist = [
        "admin","login","dashboard","wp-admin","phpmyadmin","config",
        "backup","db",".git",".env","robots.txt","sitemap.xml","api",
        "uploads","shell","panel","administrator","console","secret",
        "readme.md","index.php","wp-login.php","xmlrpc.php","install.php",
        ".htaccess","web.config","server-status","info.php","phpinfo.php"
    ]
    base = f"{urlparse(url).scheme}://{urlparse(url).netloc}"
    step(f"Bruteforcing {len(wordlist)} paths on {base}")
    for word in wordlist:
        test = f"{base}/{word}"
        attempt(f"GET /{word}")
        try:
            resp = waf_aware_get(test)
            if not resp:
                miss(f"No response — /{word}")
                continue
            if resp.status_code == 200:
                found(f"[200 OK] {test}")
                FOUND_VULNS.append({"type":"Exposed Path","url":test,"status":200})
            elif resp.status_code == 403:
                ok(f"[403] {test} — exists but blocked")
            elif resp.status_code in [301, 302]:
                ok(f"[{resp.status_code}] {test} → {resp.headers.get('Location','?')[:60]}")
            else:
                miss(f"[{resp.status_code}] /{word}")
        except:
            miss(f"Timeout — /{word}")

