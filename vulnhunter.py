def crawl(start_url, max_pages=100):
    section(f"PHASE 1 — CRAWL: {start_url}")
    log(f"  Max pages: {max_pages} | Domain: {BASE_DOMAIN}", Fore.WHITE)

    queue = deque([start_url])
    visited = set()
    count = 0

    while queue and count < max_pages:
        url = queue.popleft()
        parsed = urlparse(url)
        clean = f"{parsed.scheme}://{parsed.netloc}{parsed.path}"
        if parsed.query:
            clean += f"?{parsed.query}"
        clean = clean.rstrip("/")

        if clean in visited:
            continue
        visited.add(clean)
        count += 1
        ALL_TARGETS.add(clean)

        if is_param_url(clean):
            PARAM_URLS.add(clean)

        print(Fore.WHITE + f"  [{count}/{max_pages}] Visiting: {clean}", flush=True)

        try:
            resp = waf_aware_get(clean, allow_redirects=True)
            if not resp:
                print(Fore.YELLOW + f"          No response", flush=True)
                continue

            print(Fore.WHITE + f"          Status: {resp.status_code} | Size: {len(resp.content)} bytes", flush=True)

            ctype = resp.headers.get("Content-Type", "")
            if "text/html" not in ctype:
                print(Fore.YELLOW + f"          Skipping — not HTML", flush=True)
                continue

            soup = BeautifulSoup(resp.text, "html.parser")
            new_links = 0
            new_params = 0
            new_subs = 0

            for tag in soup.find_all("a", href=True):
                href = tag["href"].strip()
                if not href or href.startswith(("#", "javascript:", "mailto:", "tel:")):
                    continue
                full = urljoin(clean, href)
                fp = urlparse(full)
                if BASE_DOMAIN in fp.netloc:
                    norm = f"{fp.scheme}://{fp.netloc}{fp.path}"
                    if fp.query:
                        norm += f"?{fp.query}"
                    norm = norm.rstrip("/")
                    if norm not in visited:
                        queue.append(norm)
                        new_links += 1
                    if is_param_url(norm) and norm not in PARAM_URLS:
                        PARAM_URLS.add(norm)
                        new_params += 1
                    if fp.netloc != parsed.netloc and fp.netloc not in DISCOVERED_SUBDOMAINS:
                        DISCOVERED_SUBDOMAINS.add(fp.netloc)
                        new_subs += 1
                        print(Fore.MAGENTA + f"          [SUBDOMAIN] {fp.netloc}", flush=True)

            for form in soup.find_all("form", action=True):
                action = form["action"].strip()
                if action and not action.startswith("#"):
                    full = urljoin(clean, action)
                    fp = urlparse(full)
                    if BASE_DOMAIN in fp.netloc:
                        norm = f"{fp.scheme}://{fp.netloc}{fp.path}".rstrip("/")
                        if norm not in visited:
                            queue.append(norm)

            pattern = rf'([a-zA-Z0-9\-]+\.{re.escape(BASE_DOMAIN)})'
            for match in re.findall(pattern, resp.text):
                if match not in DISCOVERED_SUBDOMAINS and match != BASE_DOMAIN:
                    DISCOVERED_SUBDOMAINS.add(match)
                    ALL_TARGETS.add(f"http://{match}")
                    new_subs += 1
                    print(Fore.MAGENTA + f"          [SUBDOMAIN regex] {match}", flush=True)

            print(Fore.WHITE + f"          Links: {new_links} | Params: {new_params} | Subs: {new_subs}", flush=True)

        except requests.exceptions.Timeout:
            print(Fore.YELLOW + f"          [TIMEOUT]", flush=True)
        except Exception as e:
            print(Fore.YELLOW + f"          [ERR] {str(e)[:80]}", flush=True)

    log(f"\n[+] Crawl complete", Fore.GREEN)
    log(f"    Pages   : {count}", Fore.GREEN)
    log(f"    Params  : {len(PARAM_URLS)}", Fore.GREEN)
    log(f"    Subs    : {len(DISCOVERED_SUBDOMAINS)}", Fore.GREEN)
    log(f"    Targets : {len(ALL_TARGETS)}", Fore.GREEN)

    if PARAM_URLS:
        log(f"\n  Param URLs:", Fore.MAGENTA)
        for u in PARAM_URLS:
            log(f"    → {u}", Fore.YELLOW)

