def get_forms(url):
    try:
        r = waf_aware_get(url)
        if not r:
            return []
        return BeautifulSoup(r.text, "html.parser").find_all("form")
    except:
        return []

def get_form_details(form):
    inputs = []
    for tag in form.find_all(["input", "textarea", "select"]):
        inputs.append({
            "type": tag.attrs.get("type", "text"),
            "name": tag.attrs.get("name"),
            "value": tag.attrs.get("value", "")
        })
    return {
        "action": form.attrs.get("action", ""),
        "method": form.attrs.get("method", "get").lower(),
        "inputs": inputs
    }

def submit_form(details, url, payload):
    target_url = urljoin(url, details["action"]) if details["action"] else url
    evasion_payload = encode_payload_waf(payload)
    if evasion_payload != payload:
        attempt(f"WAF-encoded: {evasion_payload[:60]}")
    data = {}
    for inp in details["inputs"]:
        if not inp["name"]:
            continue
        if inp["type"] in ["text","search","email","password","textarea","hidden"]:
            data[inp["name"]] = evasion_payload
        else:
            data[inp["name"]] = inp["value"]
    try:
        if details["method"] == "post":
            return waf_aware_post(target_url, data=data)
        return waf_aware_get(target_url, params=data)
    except:
        return None

